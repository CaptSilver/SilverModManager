using System.Text;
using JetBrains.Annotations;
using Tomlyn;
using Tomlyn.Model;

namespace NexusMods.Library.Lock;

/// <summary>
/// A list of pinned mods in the TOML shape erm writes: one table per mod id, sorted by ordinal comparison, with the keys
/// <c>version</c>, <c>file_id</c>, <c>asset</c>, <c>sha256</c> and <c>source</c> in that order.
/// </summary>
/// <remarks>
/// The file is a pin list, so reading it fails closed: a key that is not part of the shape, a missing key or a value
/// that is not a string rejects the whole file rather than being ignored.
/// </remarks>
[PublicAPI]
public sealed class LockFile(IReadOnlyList<LockEntry> entries)
{
    public const string Header = "# Generated by SilverModManager. Pinned mod versions + hashes.";

    private static readonly string[] RequiredKeys = ["version", "asset", "sha256", "source"];
    private static readonly string[] KnownKeys = ["version", "file_id", "asset", "sha256", "source"];

    public IReadOnlyList<LockEntry> Entries { get; } = entries;

    public static LockFile Parse(string text)
    {
        TomlTable root;
        try
        {
            root = TomlSerializer.Deserialize<TomlTable>(text) ?? throw new LockException("The lock file is empty.");
        }
        catch (TomlException exception)
        {
            throw new LockException($"The lock file is not valid TOML: {exception.Message}");
        }

        var entries = new List<LockEntry>();
        foreach (var (id, value) in root)
        {
            if (value is not TomlTable table)
                throw new LockException($"The lock file has a top level value '{id}' that is not a table of one mod.");
            entries.Add(ParseEntry(id, table));
        }

        return new LockFile(entries);
    }

    private static LockEntry ParseEntry(string id, TomlTable table)
    {
        var values = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var (key, value) in table)
        {
            if (!KnownKeys.Contains(key))
                throw new LockException($"The lock entry '{id}' has an unknown key '{key}'.");
            if (value is not string text)
                throw new LockException($"The lock entry '{id}' has a '{key}' that is not a string.");
            values[key] = text;
        }

        foreach (var key in RequiredKeys)
        {
            if (!values.ContainsKey(key))
                throw new LockException($"The lock entry '{id}' has no '{key}'.");
        }

        var source = values["source"];
        if (source is not (LockSources.Nexus or LockSources.GitHub))
            throw new LockException($"The lock entry '{id}' has an unknown source '{source}'.");

        return new LockEntry(id, values["version"], values.GetValueOrDefault("file_id"), values["asset"], values["sha256"], source);
    }

    /// <summary>
    /// Writes the entries sorted by id, byte for byte the way erm writes its lock file.
    /// </summary>
    public string Write()
    {
        var builder = new StringBuilder(Header).Append('\n');
        foreach (var entry in Entries.OrderBy(entry => entry.Id, StringComparer.Ordinal))
        {
            builder.Append('\n');
            builder.Append('[').Append(TableName(entry.Id)).Append("]\n");
            AppendKey(builder, "version", entry.Version);
            if (entry.FileId is not null) AppendKey(builder, "file_id", entry.FileId);
            AppendKey(builder, "asset", entry.Asset);
            AppendKey(builder, "sha256", entry.Sha256);
            AppendKey(builder, "source", entry.Source);
        }

        return builder.ToString();
    }

    // Ids that are not plain bare keys (a dot would read as a nested table) are quoted.
    private static string TableName(string id)
    {
        var bare = id.Length > 0 && id.All(c => char.IsAsciiLetterOrDigit(c) || c is '_' or '-');
        return bare ? id : "\"" + Escape(id) + "\"";
    }

    private static void AppendKey(StringBuilder builder, string key, string value)
    {
        builder.Append(key).Append(" = \"").Append(Escape(value)).Append("\"\n");
    }

    private static string Escape(string value)
    {
        var builder = new StringBuilder(value.Length);
        foreach (var c in value)
        {
            builder.Append(c switch
            {
                '\\' => "\\\\",
                '"' => "\\\"",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                _ => c.ToString(),
            });
        }

        return builder.ToString();
    }
}
