using NexusMods.Paths;

namespace SilverModManager.Games.LoadOrderFile;

/// <summary>
/// XCOM 2's <c>DefaultModOptions.ini</c>: an <c>ActiveMods="Name"</c> line for each enabled mod under
/// <c>[Engine.XComModOptions]</c>, written the way Vortex's extension writes it. A mod's name is its folder's, which
/// must equal the name of the <c>.XComMod</c> file inside it.
/// </summary>
public sealed class XComModOptionsIniFormat : ILoadOrderFileFormat
{
    private const string Descriptor = ".XComMod";

    private const string Header = ";Generated by SilverModManager when the loadout is applied. Changes made here are replaced; reorder the mods on the Load Order page.";

    public string? ModOf(RelativePath fileInModFolder)
    {
        var parts = fileInModFolder.Path.Split('/');
        if (parts.Length != 2) return null;

        return parts[1].Equals(parts[0] + Descriptor, StringComparison.OrdinalIgnoreCase) ? parts[0] : null;
    }

    public string Render(IReadOnlyList<string> mods)
        => $"{Header}\n[Engine.XComModOptions]\n{string.Concat(mods.Select(mod => $"ActiveMods=\"{mod}\"\n"))}";
}
