using System.Text;

namespace SilverModManager.Games.Bethesda.LoadOrder.Formats;

/// <summary>
/// Shared line handling of the plugin list files: a leading generated-by comment on render, and on parse
/// comments, blank lines and CR/LF endings dropped.
/// </summary>
internal static class PluginListText
{
    private const string Header = "# Generated by SilverModManager";

    public static string Render(IEnumerable<string> lines)
    {
        var sb = new StringBuilder(Header).Append('\n');
        foreach (var line in lines) sb.Append(line).Append('\n');
        return sb.ToString();
    }

    public static IEnumerable<string> Lines(string text)
    {
        foreach (var line in text.Split('\n'))
        {
            var trimmed = line.TrimEnd('\r');
            if (trimmed.Length == 0 || trimmed[0] == '#') continue;
            yield return trimmed;
        }
    }
}
