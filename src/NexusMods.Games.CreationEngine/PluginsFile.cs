namespace NexusMods.Games.CreationEngine;

public class PluginsFile : IIntrinsicFile
{
    private readonly ICreationEngineGame _game;
    private readonly ISorter _sorter;
    private readonly ILogger<PluginsFile> _logger;
    private readonly string _activeMarker;

    private record struct Metadata(RelativePath FileName, Hash Hash, PluginHeader Header)
    {
        /// <summary>The sort id of the plugin: plugin names match without regard to case.</summary>
        public string Id => SortId(Header.FileName);
    }

    private static string SortId(string pluginName) => pluginName.ToUpperInvariant();

    /// <param name="activeMarker">Written in front of each plugin name; <c>*</c> for a list that marks active plugins, empty for one that lists only active ones.</param>
    public PluginsFile(ILogger<PluginsFile> logger, ICreationEngineGame game, ISorter sorter, string activeMarker)
    {
        _activeMarker = activeMarker;
        _game = game;
        _sorter = sorter;
        Path = game.PluginsFile;
        _logger = logger;
    }
    
    public GamePath Path { get; }
    
    public async Task Write(Stream stream, Loadout.ReadOnly loadout, Dictionary<GamePath, SyncNode> syncTree)
    {
        var plugins = new Dictionary<string, Metadata>();
        List<string> unreadable = [];
        foreach (var entry in syncTree)
        {
            if (entry.Key.Parent != _game.DataPath || !KnownCEExtensions.PluginFiles.Contains(entry.Key.Extension)) continue;
            if (!entry.Value.HaveLoadout) continue;

            var metadata = await MakeMetadata(entry);
            if (metadata is { } found)
                plugins.Add(found.Id, found);
            else
                unreadable.Add(entry.Key.FileName);
        }

        // A plugin left out of Plugins.txt is disabled, so refuse rather than write a file that switches mods off.
        if (unreadable.Count > 0)
        {
            unreadable.Sort(StringComparer.OrdinalIgnoreCase);
            throw new UnreadablePluginsException(unreadable);
        }

        if (plugins.Count == 0)
            return;
        
        var sorted = _sorter.Sort(plugins.Values.ToList(), IdSelector, plugin => RuleCreator(plugin, plugins))
            .ToList();
        _logger.LogDebug("Sorted {Count} plugin files", sorted.Count);
        
        await using var sw = new StreamWriter(stream, leaveOpen: true);
        await sw.WriteLineAsync("# Generated by SilverModManager");

        foreach (var plugin in sorted)
        {
            await sw.WriteLineAsync($"{_activeMarker}{plugin.FileName}");
        }

        await sw.FlushAsync();
    }

    private static IReadOnlyList<ISortRule<Metadata, string>> RuleCreator(Metadata metadata, Dictionary<string, Metadata> allPlugins)
    {
        var resultList = new List<ISortRule<Metadata, string>>();
        foreach (var master in metadata.Header.Masters)
        {
            // Skip missing masters here, we'll catch that in diagnostics
            if (!allPlugins.ContainsKey(SortId(master)))
                continue;
            
            resultList.Add(new After<Metadata, string>()
            {
                Other = SortId(master),
            });
        }

        // ESLs should come after ESMs
        if (metadata.FileName.Extension == KnownCEExtensions.ESL)
        {
            foreach (var other in allPlugins.Values)
            {
                if (other.FileName.Extension == KnownCEExtensions.ESM)
                    resultList.Add(new After<Metadata, string>()
                    {
                        Other = other.Id,
                    });
            }
        }
        
        // ESPs should come after ESMs and ESLs
        if (metadata.FileName.Extension == KnownCEExtensions.ESP)
        {
            foreach (var other in allPlugins.Values)
            {
                if (other.FileName.Extension == KnownCEExtensions.ESM || other.FileName.Extension == KnownCEExtensions.ESL)
                    resultList.Add(new After<Metadata, string>()
                    {
                        Other = other.Id,
                    });
            }
        }
        
        return resultList;
    }

    private static string IdSelector(Metadata metadata)
    {
        return metadata.Id;
    }

    private async ValueTask<Metadata?> MakeMetadata(KeyValuePair<GamePath, SyncNode> arg)
    {
        var relPath = arg.Key.Path.FileName;
        Hash hash;
        
        // We need to figure out if we should look at the loadout or the disk
        var syncNode = arg.Value;
        if (syncNode.Actions.HasFlag(Actions.ExtractToDisk) || syncNode.Disk.Hash == Hash.Zero || syncNode.SourceItemType == LoadoutSourceItemType.Game)
            hash = syncNode.Loadout.Hash;
        else
            hash = syncNode.Disk.Hash;
        
        var modHeader = await _game.ParseNode(syncNode, hash, relPath);
        return modHeader is null ? null : new Metadata(relPath, hash, modHeader);
    }
    


    public Task Ingest(Stream stream, Loadout.ReadOnly loadout, Dictionary<GamePath, SyncNode> syncTree, ITransaction tx)
    {
        // TODO: Implement once we have sorting
        return Task.CompletedTask;
    }
}
