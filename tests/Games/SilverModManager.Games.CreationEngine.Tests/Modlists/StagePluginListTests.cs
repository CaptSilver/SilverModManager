namespace NexusMods.Games.CreationEngine.Tests.Modlists;

/// <summary>
/// A profile's plugins.txt and loadorder.txt staged into a loadout's plugin order, as an import does it before the
/// first Apply.
/// </summary>
public class StagePluginListTests(ITestOutputHelper helper)
    : AIsolatedGameTest<StagePluginListTests, CreationEngine.SkyrimSE.SkyrimSE>(helper)
{
    protected override IServiceCollection AddServices(IServiceCollection services) => base.AddServices(services)
        .AddCreationEngine()
        .AddUniversalGameLocator<CreationEngine.SkyrimSE.SkyrimSE>(new Version("1.6.1170"), locationsFileSystem: IsolatedKnownFolders.Create);

    private IPluginSortOrderVariety Variety => Game.PluginVariety();
    private IMo2InstanceTarget Target => (IMo2InstanceTarget)Game;
    private AbsolutePath PluginsTxt => GameInstallation.Locations.ToAbsolutePath(Game.PluginsFile);

    private async Task InstallPlugins(Loadout.ReadOnly loadout, params string[] names)
    {
        var entries = names.ToDictionary(
            name => (RelativePath)$"Data/{name}",
            name => BethesdaPluginBytes.Bytes(GameRelease.SkyrimSE, name));
        var archive = await CreateTestArchive(entries);
        var library = await RegisterLocalArchive(archive.Path);
        await LoadoutManager.InstallItem(library.AsLibraryFile().AsLibraryItem(), loadout.LoadoutId);
    }

    private List<(string Name, int Index, bool IsEnabled)> StoredRows(SortOrderId id) =>
        Connection.Query<(string PluginName, int SortIndex, bool IsEnabled)>($"SELECT PluginName, SortIndex, IsEnabled FROM plugins.SortOrderItems({Connection}, {id.Value}) ORDER BY SortIndex")
            .Select(r => (r.PluginName, r.SortIndex, r.IsEnabled)).ToList();

    private async Task<(Loadout.ReadOnly Loadout, SortOrderId SortOrder)> LoadoutWithRowsTheProfileDoesNotList()
    {
        var loadout = await CreateLoadout();
        await InstallPlugins(loadout, "A.esp", "B.esp", "Mine.esp");
        // A collection in the loadout gives it a second order; the profile's list belongs to the loadout's own.
        await CreateCollection(loadout.LoadoutId, "A collection");
        await Variety.Unseed(Refresh(loadout), Connection);
        var id = await Variety.GetOrCreateSortOrderFor(loadout.LoadoutId, loadout.LoadoutId);
        return (Refresh(loadout), id);
    }

    private async Task Stage(SortOrderId id, Loadout.ReadOnly loadout, string? pluginsTxt, string? loadorderTxt)
    {
        using var tx = Connection.BeginTransaction();
        Target.StagePluginList(loadout, id, pluginsTxt, loadorderTxt, tx);
        await tx.Commit();
    }

    [Fact]
    public async Task TheProfilesLoadOrder_IsStagedAheadOfTheRowsItDoesNotList()
    {
        var (loadout, id) = await LoadoutWithRowsTheProfileDoesNotList();

        await Stage(id, loadout,
            pluginsTxt: "# This file was automatically generated by Mod Organizer.\n*B.esp\nA.esp\n*Later.esp\n*Skyrim.esm\n",
            loadorderTxt: "# This file was automatically generated by Mod Organizer.\nSkyrim.esm\nLater.esp\nA.esp\nB.esp\n");

        var rows = StoredRows(id);
        rows.Select(r => r.Name).Should().Equal("Later.esp", "A.esp", "B.esp", "Mine.esp");
        rows.Select(r => r.Index).Should().OnlyHaveUniqueItems();
        rows.Select(r => r.IsEnabled).Should().Equal(true, false, true, true);
        PluginSortOrder.Load(Connection.Db, id.Value).SeededFromGameFile.Should().BeTrue();
        Variety.StoredOrder(Refresh(loadout)).Select(r => r.Name).Should().Equal(
            ["A.esp", "B.esp", "Mine.esp"], "Later.esp has no plugin in the loadout yet, so its row stays hidden");
    }

    [Fact]
    public async Task WithNoLoadorderFile_ThePluginsFileGivesTheOrder()
    {
        var (loadout, id) = await LoadoutWithRowsTheProfileDoesNotList();

        await Stage(id, loadout, pluginsTxt: "# generated\nB.esp\n*A.esp\n", loadorderTxt: null);

        StoredRows(id).Select(r => (r.Name, r.IsEnabled)).Should().Equal(("B.esp", false), ("A.esp", true), ("Mine.esp", true));
    }

    [Fact]
    public async Task TheStagedOrder_IsWhatTheNextApplyWrites_WithoutTheSeedReplacingIt()
    {
        var (loadout, id) = await LoadoutWithRowsTheProfileDoesNotList();
        PluginsTxt.Parent.CreateDirectory();
        await PluginsTxt.WriteAllTextAsync("*Mine.esp\n*B.esp\n*A.esp\n");

        await Stage(id, loadout, "*B.esp\nA.esp\n", "A.esp\nB.esp\n");
        await Synchronizer.Synchronize(Refresh(loadout));

        var lines = (await PluginsTxt.ReadAllTextAsync()).Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        lines.Skip(1).Should().Equal("A.esp", "*B.esp", "*Mine.esp");
    }

    [Fact]
    public async Task WithNeitherFile_StagingIsRefused()
    {
        var (loadout, id) = await LoadoutWithRowsTheProfileDoesNotList();

        var act = () => Stage(id, loadout, null, null);

        await act.Should().ThrowAsync<ArgumentException>();
    }
}
