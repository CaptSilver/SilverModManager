using FluentAssertions;
using Mutagen.Bethesda;
using SilverModManager.Abstractions.Games;
using SilverModManager.Abstractions.Loadouts;
using SilverModManager.Abstractions.Loadouts.Synchronizers;
using SilverModManager.Sdk.Loadouts;
using NexusMods.Paths;
using SilverModManager.Sdk.Games;
using Xunit;

namespace SilverModManager.Games.CreationEngine.Tests.RoundTrip;

/// <summary>
/// Adds the plugin list to the round trip: a real plugin in a mod shows up in the title's plugins file with its
/// marker, and is gone again once the mod is removed. Every change reaches the file on a single Synchronize.
/// </summary>
public abstract class ACreationEngineRoundTripTest<TTest, TGame>(ITestOutputHelper helper) : ABethesdaRoundTripTest<TTest, TGame>(helper)
    where TTest : class
    where TGame : class, IGame
{
    protected const string Header = "# Generated by SilverModManager";

    protected abstract GamePath PluginsFile { get; }
    protected abstract string Marker { get; }
    protected abstract GameRelease Release { get; }

    /// <summary>Other files the title's list mechanism writes beside <see cref="PluginsFile"/>.</summary>
    protected virtual GamePath[] CompanionFiles => [];

    protected byte[] PluginBytes(string fileName) => BethesdaPluginBytes.Bytes(Release, fileName);

    protected async Task<string[]> PluginLines()
    {
        var file = OnDisk(PluginsFile);
        if (!file.FileExists) return [];
        return (await file.ReadAllTextAsync()).Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
    }

    protected Task<LoadoutItemGroup.ReadOnly> InstallPlugin(Loadout.ReadOnly loadout, string fileName) =>
        InstallMod(loadout, new Dictionary<RelativePath, byte[]> { { $"Data/{fileName}", PluginBytes(fileName) } });

    protected async Task Apply(Loadout.ReadOnly loadout) => await Synchronizer.Synchronize(Refresh(loadout));

    [Theory]
    [InlineData("default")]
    [InlineData("copy")]
    public async Task PluginsReachTheFileOnTheSyncThatFollowsEachChange(string backend)
    {
        var loadout = await CreateLoadoutOn(backend);

        var first = await InstallPlugin(loadout, "First.esp");
        await Apply(loadout);
        var lines = await PluginLines();
        lines[0].Should().Be(Header);
        lines.Skip(1).Should().Equal($"{Marker}First.esp");

        var second = await InstallPlugin(loadout, "Second.esp");
        await Apply(loadout);
        (await PluginLines()).Skip(1).Should().BeEquivalentTo([$"{Marker}First.esp", $"{Marker}Second.esp"]);

        await LoadoutManager.RemoveItems([first.LoadoutItemGroupId]);
        await Apply(loadout);
        (await PluginLines()).Skip(1).Should().Equal($"{Marker}Second.esp");

        await LoadoutManager.RemoveItems([second.LoadoutItemGroupId]);
        await Apply(loadout);
        (await PluginLines()).Should().NotContain(line => line.EndsWith(".esp"));
    }

    [Fact]
    public async Task TheSynchronizerOffersThePluginsFileForARealLoadout()
    {
        var loadout = await CreateLoadout();

        var offered = ((ALoadoutSynchronizer)Synchronizer).IntrinsicFiles(loadout);

        offered.Keys.Should().BeEquivalentTo([PluginsFile, .. CompanionFiles]);
        offered.Values.Should().AllBeOfType<CreationEngine.PluginsFile>();
    }

    [Fact]
    public async Task AnEmptySyncBeforeTheFirstInstallDoesNotDelayTheListing()
    {
        var loadout = await CreateLoadoutOn("default");
        await Apply(loadout);

        await InstallPlugin(loadout, "First.esp");
        await Apply(loadout);

        (await PluginLines()).Should().Contain($"{Marker}First.esp");
    }
}
