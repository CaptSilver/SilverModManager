namespace SilverModManager.Games.CreationEngine.Tests.SortOrder;

/// <summary>
/// What happens when the game edits Plugins.txt between two Applies: the app's list goes back over it in the
/// same Apply, nothing in the stored order changes, and the user is told what was replaced.
/// </summary>
public class PluginListReplacementTests(ITestOutputHelper helper)
    : AIsolatedGameTest<PluginListReplacementTests, CreationEngine.SkyrimSE.SkyrimSE>(helper)
{
    private const string Header = "# Generated by SilverModManager";

    protected override IServiceCollection AddServices(IServiceCollection services) => base.AddServices(services)
        .AddCreationEngine()
        .AddUniversalGameLocator<CreationEngine.SkyrimSE.SkyrimSE>(new Version("1.6.1170"), locationsFileSystem: IsolatedKnownFolders.Create);

    private AbsolutePath PluginsTxt => GameInstallation.Locations.ToAbsolutePath(Game.PluginsFile);

    private IPluginSortOrderVariety Variety => Game.SortOrderManager.GetSortOrderVarieties().OfType<IPluginSortOrderVariety>().Single();

    private SortOrderId SortOrderOf(Loadout.ReadOnly loadout) => Variety.GetSortOrderIdFor(loadout.LoadoutId, Connection.Db).Value;

    private async Task Apply(Loadout.ReadOnly loadout) => await Synchronizer.Synchronize(Refresh(loadout));

    private async Task<string[]> Lines()
    {
        var lines = (await PluginsTxt.ReadAllTextAsync()).Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        lines[0].Should().Be(Header);
        return lines.Skip(1).ToArray();
    }

    private async Task InstallPlugins(Loadout.ReadOnly loadout, params string[] names)
    {
        var entries = names.ToDictionary(
            name => (RelativePath)$"Data/{name}",
            name => BethesdaPluginBytes.Bytes(GameRelease.SkyrimSE, name));
        var archive = await CreateTestArchive(entries);
        var library = await RegisterLocalArchive(archive.Path);
        await LoadoutManager.InstallItem(library.AsLibraryFile().AsLibraryItem(), loadout.LoadoutId);
    }

    private string[] Notices(Loadout.ReadOnly loadout) =>
        Connection.Db.Datoms(PluginListNotice.SortOrder, SortOrderOf(loadout))
            .Select(d => PluginListNotice.Load(Connection.Db, d.E).Summary).ToArray();

    private async Task<List<Diagnostic>> Diagnose(Loadout.ReadOnly loadout)
    {
        var found = new List<Diagnostic>();
        await foreach (var diagnostic in new PluginListReplacedEmitter(Game).Diagnose(Refresh(loadout), CancellationToken.None))
            found.Add(diagnostic);
        return found;
    }

    private static string[] Stored(IPluginSortOrderVariety variety, Loadout.ReadOnly loadout) =>
        variety.StoredOrder(loadout).Select(r => $"{r.SortIndex}:{r.Name}:{r.IsEnabled}").ToArray();

    // A managed loadout whose first Apply has written the app's list, so the next one has a previous state.
    private async Task<Loadout.ReadOnly> AppliedLoadout()
    {
        var loadout = await CreateLoadout();
        await InstallPlugins(loadout, "A.esp", "B.esp", "C.esp", "D.esp");
        await Apply(loadout);
        (await Lines()).Should().Equal("*A.esp", "*B.esp", "*C.esp", "*D.esp");
        return loadout;
    }

    [Fact]
    public async Task AnEditOfTheFile_IsReplacedInTheSameApply_WithoutTouchingTheStoredOrder()
    {
        var loadout = await AppliedLoadout();
        var before = Stored(Variety, Refresh(loadout));

        await PluginsTxt.WriteAllTextAsync("*A.esp\nB.esp\n*D.esp\n*C.esp\n");
        await Apply(loadout);

        (await Lines()).Should().Equal("*A.esp", "*B.esp", "*C.esp", "*D.esp");
        Stored(Variety, Refresh(loadout)).Should().Equal(before);
        var notice = Notices(loadout).Should().ContainSingle().Subject;
        notice.Should().Contain("1 switched off").And.Contain("1 moved").And.Contain("B.esp");
    }

    [Fact]
    public async Task TheNotice_BecomesAWarningDiagnosticThatNamesTheChange()
    {
        var loadout = await AppliedLoadout();
        await PluginsTxt.WriteAllTextAsync("*A.esp\nB.esp\n*C.esp\n*D.esp\n");
        await Apply(loadout);

        var diagnostic = (await Diagnose(loadout)).Should().ContainSingle().Subject;

        diagnostic.Severity.Should().Be(DiagnosticSeverity.Warning);
        diagnostic.FormatSummary(new PlainDiagnosticWriter()).Should().Contain("1 switched off").And.Contain("B.esp");
    }

    [Fact]
    public async Task AFurtherApplyWithNoEdit_ClearsTheNotice()
    {
        var loadout = await AppliedLoadout();
        await PluginsTxt.WriteAllTextAsync("*A.esp\nB.esp\n*C.esp\n*D.esp\n");
        await Apply(loadout);
        Notices(loadout).Should().HaveCount(1);

        await Apply(loadout);

        Notices(loadout).Should().BeEmpty();
        (await Diagnose(loadout)).Should().BeEmpty();
    }

    // The Apply clears the earlier notice before it compares the file, so the new one must not be built on it.
    [Fact]
    public async Task ASecondEdit_ReplacesTheNoticeOfTheFirst()
    {
        var loadout = await AppliedLoadout();
        await PluginsTxt.WriteAllTextAsync("*A.esp\nB.esp\n*C.esp\n*D.esp\n");
        await Apply(loadout);
        Notices(loadout).Should().ContainSingle().Which.Should().Contain("B.esp");

        await PluginsTxt.WriteAllTextAsync("*A.esp\n*B.esp\nC.esp\n*D.esp\n");
        await Apply(loadout);

        var notice = Notices(loadout).Should().ContainSingle().Subject;
        notice.Should().Contain("1 switched off").And.Contain("C.esp").And.NotContain("B.esp");
        (await Diagnose(loadout)).Should().ContainSingle();
        (await Lines()).Should().Equal("*A.esp", "*B.esp", "*C.esp", "*D.esp");
    }

    [Fact]
    public async Task AHandAddedUnknownPluginLine_ProducesNoNotice()
    {
        var loadout = await AppliedLoadout();

        await PluginsTxt.WriteAllTextAsync("*A.esp\n*B.esp\n*Ghost.esp\n*C.esp\n*D.esp\n");
        await Apply(loadout);

        Notices(loadout).Should().BeEmpty();
        (await Lines()).Should().Equal("*A.esp", "*B.esp", "*C.esp", "*D.esp");
    }

    [Fact]
    public async Task AnEditAfterAReset_IsNotNoticedAndTheFileIsWritten()
    {
        var loadout = await AppliedLoadout();
        await PluginsTxt.WriteAllTextAsync("*A.esp\nB.esp\n*D.esp\n*C.esp\n");
        await Synchronizer.ResetToOriginalGameState(GameInstallation, GameInstallation.LocatorResult.LocatorIds.ToArray());
        var before = Stored(Variety, Refresh(loadout));

        await Apply(loadout);

        Notices(loadout).Should().BeEmpty();
        Stored(Variety, Refresh(loadout)).Should().Equal(before);
        (await Lines()).Should().Equal("*A.esp", "*B.esp", "*C.esp", "*D.esp");
    }

    [Fact]
    public async Task AMoveRunningWhileTheNoticeIsWritten_Succeeds()
    {
        var loadout = await AppliedLoadout();
        var id = SortOrderOf(loadout);
        var staleDb = Connection.Db;

        await PluginsTxt.WriteAllTextAsync("*A.esp\nB.esp\n*C.esp\n*D.esp\n");
        await Apply(loadout);
        Notices(loadout).Should().HaveCount(1);

        await Variety.MoveItems(id, [new SortItemKey<string>("d.esp")], new SortItemKey<string>("a.esp"), TargetRelativePosition.BeforeTarget, staleDb);

        Variety.StoredOrder(Refresh(loadout)).Select(r => r.Name).Should().Equal("D.esp", "A.esp", "B.esp", "C.esp");
    }
}
