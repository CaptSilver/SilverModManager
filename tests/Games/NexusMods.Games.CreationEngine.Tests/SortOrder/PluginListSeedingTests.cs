using FluentAssertions;
using Microsoft.Extensions.DependencyInjection;
using Mutagen.Bethesda;
using NexusMods.Abstractions.Games;
using NexusMods.Abstractions.Loadouts;
using NexusMods.Games.CreationEngine.Models;
using NexusMods.Games.CreationEngine.SortOrder;
using NexusMods.Games.TestFramework;
using NexusMods.Paths;
using NexusMods.Sdk.Games;
using NexusMods.Sdk.Loadouts;
using NexusMods.StandardGameLocators.TestHelpers;
using Xunit;

namespace NexusMods.Games.CreationEngine.Tests.SortOrder;

/// <summary>
/// The Skyrim SE plugin list as the app renders it from the stored order: seeded once from the file the game
/// already has, and rendered from the order and switches after that.
/// </summary>
public class PluginListSeedingTests(ITestOutputHelper helper)
    : AIsolatedGameTest<PluginListSeedingTests, CreationEngine.SkyrimSE.SkyrimSE>(helper)
{
    private const string Header = "# Generated by SilverModManager";

    protected override IServiceCollection AddServices(IServiceCollection services) => base.AddServices(services)
        .AddCreationEngine()
        .AddUniversalGameLocator<CreationEngine.SkyrimSE.SkyrimSE>(new Version("1.6.1170"), locationsFileSystem: IsolatedKnownFolders.Create);

    private AbsolutePath PluginsTxt => GameInstallation.Locations.ToAbsolutePath(Game.PluginsFile);

    private IPluginSortOrderVariety Variety => Game.SortOrderManager.GetSortOrderVarieties().OfType<IPluginSortOrderVariety>().Single();

    private async Task GameHasAPluginsFile(string content)
    {
        PluginsTxt.Parent.CreateDirectory();
        await PluginsTxt.WriteAllTextAsync(content);
    }

    private async Task<string[]> Lines()
    {
        var text = await PluginsTxt.ReadAllTextAsync();
        var lines = text.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        lines[0].Should().Be(Header);
        return lines.Skip(1).ToArray();
    }

    private async Task InstallPlugins(Loadout.ReadOnly loadout, params string[] names)
    {
        var entries = names.ToDictionary(
            name => (RelativePath)$"Data/{name}",
            name => BethesdaPluginBytes.Bytes(GameRelease.SkyrimSE, name));
        var archive = await CreateTestArchive(entries);
        var library = await RegisterLocalArchive(archive.Path);
        await LoadoutManager.InstallItem(library.AsLibraryFile().AsLibraryItem(), loadout.LoadoutId);
    }

    private async Task Apply(Loadout.ReadOnly loadout) => await Synchronizer.Synchronize(Refresh(loadout));

    private SortOrderId SortOrderOf(Loadout.ReadOnly loadout) => Variety.GetSortOrderIdFor(loadout.LoadoutId, Connection.Db).Value;

    private bool IsSeeded(Loadout.ReadOnly loadout) => PluginSortOrder.Load(Connection.Db, SortOrderOf(loadout).Value).SeededFromGameFile;

    // Creating a loadout already syncs it once, which seeds from whatever the game has then. This puts a loadout
    // back in the state of one made before the seed existed, with its plugins installed and the order not filled.
    private async Task Unseed(Loadout.ReadOnly loadout)
    {
        await Variety.ReconcileSortOrder(SortOrderOf(loadout));
        using var tx = Connection.BeginTransaction();
        tx.Add(SortOrderOf(loadout).Value, PluginSortOrder.SeededFromGameFile, false);
        await tx.Commit();
    }

    private static SortItemKey<string> Key(string name) => new(name.ToLowerInvariant());

    [Fact]
    public async Task TheFirstApply_ReproducesTheOrderAndStarStateOfTheFileTheGameHad()
    {
        var loadout = await CreateLoadout();
        await InstallPlugins(loadout, "A.esp", "B.esp", "C.esp");
        await Unseed(loadout);
        await GameHasAPluginsFile("# the user's list\n*C.esp\nA.esp\n*B.esp\n");

        await Apply(loadout);

        (await Lines()).Should().Equal("*C.esp", "A.esp", "*B.esp");
    }

    [Fact]
    public async Task ManagingAPrefixThatHasPluginsAndAList_KeepsTheListsOrderAndStarsOnTheNextApply()
    {
        // The plugins are only files in the folder when the loadout is made, so the seed sees them in the list
        // before the loadout owns them; the order and switches have to survive until it does.
        foreach (var name in new[] { "A.esp", "B.esp", "C.esp" })
        {
            var file = GameInstallation.Locations.ToAbsolutePath(new GamePath(LocationId.Game, $"Data/{name}"));
            file.Parent.CreateDirectory();
            await file.WriteAllBytesAsync(BethesdaPluginBytes.Bytes(GameRelease.SkyrimSE, name));
        }
        await GameHasAPluginsFile("# the user's list\n*C.esp\nA.esp\n*B.esp\n");

        var loadout = await CreateLoadout();
        await Apply(loadout);

        (await Lines()).Should().Equal("*C.esp", "A.esp", "*B.esp");
    }

    [Fact]
    public async Task ThePluginsTheGamesFileDoesNotMention_FollowTheListedOnesSwitchedOn()
    {
        var loadout = await CreateLoadout();
        await InstallPlugins(loadout, "A.esp", "B.esp", "Mine.esp");
        await Unseed(loadout);
        await GameHasAPluginsFile("B.esp\n*A.esp\n");

        await Apply(loadout);

        (await Lines()).Should().Equal("B.esp", "*A.esp", "*Mine.esp");
    }

    [Fact]
    public async Task WithNoFileOnDisk_TheSeedStoresTheDefaultOrderAndSetsTheFlag()
    {
        var loadout = await CreateLoadout();
        await InstallPlugins(loadout, "Zed.esp", "Core.esm", "Alpha.esp");
        await Unseed(loadout);
        PluginsTxt.Delete();

        await Apply(loadout);

        IsSeeded(loadout).Should().BeTrue();
        (await Lines()).Should().Equal("*Core.esm", "*Alpha.esp", "*Zed.esp");
    }

    [Fact]
    public async Task TheSecondApplyAfterAMoveAndASwitch_WritesTheMovedOrderAndTheSwitch()
    {
        var loadout = await CreateLoadout();
        await InstallPlugins(loadout, "A.esp", "B.esp", "C.esp");
        await Unseed(loadout);
        await GameHasAPluginsFile("*A.esp\n*B.esp\n*C.esp\n");
        await Apply(loadout);
        (await Lines()).Should().Equal("*A.esp", "*B.esp", "*C.esp");

        await Variety.MoveItemDelta(SortOrderOf(loadout), Key("C.esp"), -2);
        await Variety.SetEnabled(SortOrderOf(loadout), Key("B.esp"), false);
        await Apply(loadout);

        (await Lines()).Should().Equal("*C.esp", "*A.esp", "B.esp");
    }

    [Fact]
    public async Task TheSeedRunsOnce_ALaterEditOfTheGamesFileIsNotAdopted()
    {
        var loadout = await CreateLoadout();
        await InstallPlugins(loadout, "A.esp", "B.esp");
        await Unseed(loadout);
        await GameHasAPluginsFile("*A.esp\n*B.esp\n");
        await Apply(loadout);
        IsSeeded(loadout).Should().BeTrue();

        await GameHasAPluginsFile("B.esp\n*A.esp\n");
        await Apply(loadout);

        (await Lines()).Should().Equal("*A.esp", "*B.esp");
    }

    [Fact]
    public async Task APluginInstalledJustBeforeApply_HasItsRowAndIsInTheFile()
    {
        var loadout = await CreateLoadout();
        await InstallPlugins(loadout, "First.esp");
        await Apply(loadout);

        await InstallPlugins(loadout, "Fresh.esp");
        await Apply(loadout);

        Variety.StoredOrder(Refresh(loadout)).Select(row => row.Name).Should().Contain("Fresh.esp");
        (await Lines()).Should().Equal("*First.esp", "*Fresh.esp");
    }

    [Fact]
    public async Task SwitchingToAnUnseededLoadout_SeedsIt()
    {
        var first = await CreateLoadout();
        await Apply(first);
        var second = await CreateLoadout();
        await InstallPlugins(second, "Mine.esp");
        await Unseed(second);

        await Apply(second);

        IsSeeded(second).Should().BeTrue();
        (await Lines()).Should().Equal("*Mine.esp");
    }

    [Fact]
    public async Task TheDiagnosticsPaths_NeverSeed()
    {
        var loadout = await CreateLoadout();
        await InstallPlugins(loadout, "A.esp");
        await Unseed(loadout);

        await Synchronizer.BuildSyncTree(Refresh(loadout));

        IsSeeded(loadout).Should().BeFalse("building a tree for diagnostics must not seed");
    }
}
