using FluentAssertions;
using SilverModManager.Library.Lock;
using Xunit;

namespace SilverModManager.Library.Tests.Lock;

public class LockFileTests
{
    internal static string FixtureText => File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "Resources", "erm-mods.lock.toml"));

    private static string WithoutHeader(string text) => string.Join('\n', text.Split('\n').Skip(1));

    [Fact]
    public void ParsingTheFixtureReadsEveryTable()
    {
        var lockFile = LockFile.Parse(FixtureText);

        lockFile.Entries.Should().HaveCount(FixtureText.Split('\n').Count(line => line.StartsWith('[')));
        var fov = lockFile.Entries.Single(entry => entry.Id == "adjust-the-fov");
        fov.Should().Be(new LockEntry("adjust-the-fov", "2.0", "5087", "AdjustTheFov-325-2-0-1653830963.zip", "339a27e94780c1550380d0fbc81026265da0539f95cfd004b012ec5c99c8323b", "nexus"));

        var host = lockFile.Entries.Single(entry => entry.Id == "me3-host");
        host.FileId.Should().BeNull("only Nexus Mods entries have a file id");
        host.Source.Should().Be("github");
    }

    [Fact]
    public void WritingWhatWasParsedReproducesTheFixtureBesidesTheHeader()
    {
        var written = LockFile.Parse(FixtureText).Write();

        written.Split('\n')[0].Should().Be("# Generated by SilverModManager. Pinned mod versions + hashes.");
        WithoutHeader(written).Should().Be(WithoutHeader(FixtureText));
    }

    [Fact]
    public void EntriesAreWrittenSortedByOrdinalIdWhateverTheirOrder()
    {
        var entries = new[]
        {
            new LockEntry("b-mod", "1", null, "b.zip", "ab", "github"),
            new LockEntry("B-mod", "1", "9", "B.zip", "cd", "nexus"),
            new LockEntry("a-mod", "1", null, "a.zip", "ef", "github"),
        };

        var written = new LockFile(entries).Write();

        written.Split('\n').Where(line => line.StartsWith('[')).Should().Equal("[B-mod]", "[a-mod]", "[b-mod]");
    }

    [Fact]
    public void ValuesWithQuotesAndBackslashesSurviveARoundTrip()
    {
        var entry = new LockEntry("odd", "1.0 \"beta\"", null, "a\\b\"c.zip", "ab", "github");

        var parsed = LockFile.Parse(new LockFile([entry]).Write());

        parsed.Entries.Should().ContainSingle().Which.Should().Be(entry);
    }

    [Fact]
    public void AnUnknownKeyFailsTheParseAndNamesTheTable()
    {
        var text = "[some-mod]\nversion = \"1\"\nasset = \"a.zip\"\nsha256 = \"ab\"\nsource = \"github\"\nmirror = \"x\"\n";

        var act = () => LockFile.Parse(text);

        act.Should().Throw<LockException>().Which.Message.Should().Contain("some-mod").And.Contain("mirror");
    }

    [Fact]
    public void ATableMissingARequiredKeyFailsTheParseAndNamesTheTable()
    {
        var act = () => LockFile.Parse("[some-mod]\nversion = \"1\"\nsource = \"github\"\n");

        act.Should().Throw<LockException>().Which.Message.Should().Contain("some-mod").And.Contain("asset");
    }

    [Fact]
    public void AValueThatIsNotAStringFailsTheParse()
    {
        var act = () => LockFile.Parse("[some-mod]\nversion = \"1\"\nfile_id = 5087\nasset = \"a.zip\"\nsha256 = \"ab\"\nsource = \"nexus\"\n");

        act.Should().Throw<LockException>().Which.Message.Should().Contain("some-mod").And.Contain("file_id");
    }

    [Fact]
    public void AThunderstoreSourceParsesAndIsWrittenSortedWithTheSameKeyOrder()
    {
        const string text = "[b-mod]\nversion = \"1\"\nasset = \"b.zip\"\nsha256 = \"ab\"\nsource = \"github\"\n\n" +
                            "[a-mod]\nversion = \"4.2.0\"\nasset = \"Zehs-REPOLib-4.2.0.zip\"\nsha256 = \"cd\"\nsource = \"thunderstore\"\n";

        var lockFile = LockFile.Parse(text);

        lockFile.Entries.Single(entry => entry.Id == "a-mod").Source.Should().Be(LockSources.Thunderstore);
        WithoutHeader(lockFile.Write()).Should().Be(
            "\n[a-mod]\nversion = \"4.2.0\"\nasset = \"Zehs-REPOLib-4.2.0.zip\"\nsha256 = \"cd\"\nsource = \"thunderstore\"\n" +
            "\n[b-mod]\nversion = \"1\"\nasset = \"b.zip\"\nsha256 = \"ab\"\nsource = \"github\"\n");
    }

    [Fact]
    public void AnUnknownSourceFailsTheParse()
    {
        var act = () => LockFile.Parse("[some-mod]\nversion = \"1\"\nasset = \"a.zip\"\nsha256 = \"ab\"\nsource = \"ftp\"\n");

        act.Should().Throw<LockException>().Which.Message.Should().Contain("some-mod").And.Contain("ftp");
    }

    [Fact]
    public void AnEmptySha256ParsesSoThePolicyLayerCanRejectIt()
    {
        var lockFile = LockFile.Parse("[some-mod]\nversion = \"1\"\nasset = \"a.zip\"\nsha256 = \"\"\nsource = \"github\"\n");

        lockFile.Entries.Single().Sha256.Should().BeEmpty();
    }

    [Fact]
    public void InvalidTomlFailsWithALockException()
    {
        var act = () => LockFile.Parse("[some-mod\nversion = ");

        act.Should().Throw<LockException>();
    }
}
