        var archive = await AddZip("a.zip", new() { ["base.bin"] = [1, 2, 3] });
        var list = new ListBuilder();
        list.Archives.Add(archive);
        var good = new PatchedFromArchive(P("mods/A/good.bin"), Hash64(new byte[] { 1, 2, 3, 4 }), 4, new ArchiveHashPath(archive.XxHash64, [P("base.bin")]), Hash64(new byte[] { 1, 2, 3 }), list.Blob([4]));
        var bad = good with { To = P("mods/A/bad.bin"), XxHash64 = Hash.From(9) };
        list.Directives.AddRange([good, bad]);
        var loadout = await CreateLoadout();
        var modlist = await AddModlist(list.ToList(), list.Blobs);

        var (_, group) = await Install(loadout, modlist, new InstallOptions(false, new HashSet<RelativePath>()));

        var tree = TreeOf(group);
        tree["A"].Should().ContainKey("Game/Data/good.bin").WhoseValue.Should().Be(new byte[] { 1, 2, 3, 4 }.xxHash3());
        tree["A"].Should().NotContainKey("Game/Data/bad.bin");
        SkipsOf(group).Should().ContainSingle(s => s.To == "mods/A/bad.bin" && s.Kind == SkipKind.HashMismatch);
    }

