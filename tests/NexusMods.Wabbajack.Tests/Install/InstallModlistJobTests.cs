    /// <summary>The fixture list, with its directives in the reverse of the order they are written in.</summary>
    private async Task<(ListBuilder List, ArchiveEntry ArchiveA, ArchiveEntry ArchiveB, ArchiveEntry Enb)> FixtureList()
    {
        var archiveA = await AddZip("a.zip", new() { ["plugin/Plugin A.esp"] = PluginA, ["meshes/x.nif"] = MeshA, ["root.dll"] = RootDll });
        var archiveB = await AddZip("b.zip", new() { ["B.esp"] = PluginB });
