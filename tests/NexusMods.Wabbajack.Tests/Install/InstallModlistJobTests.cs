        var exe = GameExeArchive();

        var list = new ListBuilder();
        list.Archives.AddRange([archiveA, archiveB, enb, exe]);

        // Written in the order a list is written in, then reversed so the job has to sort them.
        list.Directives.AddRange(
        [
            list.Member("mods/A/Plugin A.esp", archiveA, "plugin/Plugin A.esp", PluginA),
            list.Member("mods/A/meshes/x.nif", archiveA, "meshes/x.nif", MeshA),
            list.Member("mods/A/Root/root.dll", archiveA, "root.dll", RootDll),
            list.Member("mods/B/B.esp", archiveB, "B.esp", PluginB),
            list.Remapped("mods/A/SKSE/Plugins/x.ini", MarkerText),
            list.Inline("profiles/Default/modlist.txt", ModlistTxt),
            list.Inline("profiles/Default/plugins.txt", PluginsTxt),
            list.Inline("profiles/Default/loadorder.txt", LoadorderTxt),
            list.Inline("profiles/Default/skyrim.ini", "[General]\nsLanguage=ENGLISH\n"),
            list.Inline("profiles/Default/skyrimprefs.ini", "[Display]\niSize W=1920\n"),
            list.Member("overwrite/over.txt", archiveB, "B.esp", PluginB),
            new FromArchive(P("Stock Game/SkyrimSE.exe"), Hash64(StubExe), StubExe.Length, new ArchiveHashPath(exe.XxHash64, [])),
            list.Member("Stock Game/d3d11.dll", enb, "d3d11.dll", EnbDll),
            list.Remapped("ModOrganizer.ini", ModOrganizerIni),
            list.Inline("ModOrganizer.exe", "exe"),
            list.Inline("nxmhandler.ini", "[handlers]"),
            list.Inline("pythoncore.zip", "zip"),
            list.Inline("Default.compiler_settings", "{}"),
            list.Meta("downloads/a.zip.meta", "[General]"),
        ]);
        list.Directives.Reverse();
        return (list, archiveA, archiveB, enb);
    }

    [Fact]
    public async Task AListInstallsAsMo2LaysItOutAndIsEnabledOnceOrdered()
    {
        var (fixture, archiveA, archiveB, enb) = await FixtureList();
        var loadout = await CreateLoadout();
        var modlist = await AddModlist(fixture.ToList(), fixture.Blobs);

        var (job, group) = await Install(loadout, modlist, new InstallOptions(false, new HashSet<RelativePath>()));

        var tree = TreeOf(group);
        tree.Keys.Should().BeEquivalentTo("A", "B", "Overwrite", "Profile settings", "Stock Game");
        tree["A"].Keys.Should().BeEquivalentTo("Game/Data/Plugin A.esp", "Game/Data/meshes/x.nif", "Game/root.dll", "Game/Data/SKSE/Plugins/x.ini");
        tree["A"]["Game/Data/Plugin A.esp"].Should().Be(PluginA.xxHash3());
        tree["A"]["Game/root.dll"].Should().Be(RootDll.xxHash3());
        tree["B"].Keys.Should().BeEquivalentTo("Game/Data/B.esp");
        tree["Overwrite"].Keys.Should().BeEquivalentTo("Game/Data/over.txt");
        tree["Profile settings"].Keys.Should().BeEquivalentTo("Preferences/Skyrim.ini", "Preferences/SkyrimPrefs.ini");
        tree["Stock Game"].Keys.Should().BeEquivalentTo("Game/d3d11.dll");

        WabbajackSkippedFile.All(Connection.Db).Should().BeEmpty();
        group.AsCollectionGroup().AsLoadoutItemGroup().AsLoadoutItem().IsDisabled.Should().BeFalse("nothing was skipped, so the ordered list is enabled");
        group.AsCollectionGroup().IsReadOnly.Should().BeFalse();

        job.Progress.DroppedCount.Should().Be(9, "four seeds, four Mod Organizer files at the root and one download's .meta");
        var members = new[] { PluginA, MeshA, RootDll, PluginB, EnbDll }.Sum(b => (long)b.Length);
        job.Progress.EstimatedExtractedSize.Value.Should().Be((ulong)members);
        job.Progress.IsEstimateLowerBound.Should().BeFalse();
        job.Progress.Phase.Should().Be(InstallPhase.Order);
        job.Progress.DoneItems.Should().Be(job.Progress.TotalItems);
    }

    [Fact]
    public async Task ARemappedFileGetsThePathsOfTheStubGameAndTheListsExtrasFolder()
    {
        var (fixture, _, _, _) = await FixtureList();
        var loadout = await CreateLoadout();
        var modlist = await AddModlist(fixture.ToList(), fixture.Blobs);

        var (_, group) = await Install(loadout, modlist, new InstallOptions(false, new HashSet<RelativePath>()));

        var hash = TreeOf(group)["A"]["Game/Data/SKSE/Plugins/x.ini"];
        await using var stream = await FileStore.GetFileStream(hash);
        var text = Encoding.UTF8.GetString(await ReadAll(stream));

        var gameRoot = loadout.InstallationInstance.Locations.ToAbsolutePath(new GamePath(LocationId.Game, RelativePath.Empty)).ToString();
        var extras = ExtrasOf(group).ToString();
        text.Should().NotContain("{--||");
        AssertSpellings(text, "game", gameRoot);
        AssertSpellings(text, "mo2", extras);
        AssertSpellings(text, "dl", extras + "/downloads");
        Directory.Exists(extras + "/downloads").Should().BeTrue("the downloads folder the list points at is created empty");
    }

    private static void AssertSpellings(string text, string prefix, string hostPath)
    {
        var windows = "Z:" + hostPath.Replace('/', '\\');
        text.Should().Contain($"{prefix}={windows}\n");
        text.Should().Contain($"{prefix}2={windows.Replace("\\", "\\\\")}\n");
        text.Should().Contain($"{prefix}3={windows.Replace('\\', '/')}\n");
    }

