/// <summary>What the install does after the files are written: the order of the mod groups, the plugin list, and enabling the list.</summary>
public class InstallOrderTests(ITestOutputHelper helper) : InstallTestBase<InstallOrderTests>(helper)
{
    private const string ModlistTxt = "# This file was automatically generated by Mod Organizer.\n+B\n+Divider_separator\n+A\n-C\n";
    private const string PluginsTxt = "# This file was automatically generated by Mod Organizer.\n*A.esp\n*B.esp\n";
    private const string LoadorderTxt = "# This file was automatically generated by Mod Organizer.\nA.esp\nB.esp\n";

    private static readonly byte[] EnbFromStockGame = "enb of the stock game"u8.ToArray();
    private static readonly byte[] EnbFromModA = "enb of mod a"u8.ToArray();
    private static readonly byte[] RootDll = "root dll"u8.ToArray();

    /// <summary>An empty Skyrim SE plugin: just the TES4 record with its HEDR, which is all the plugin list reads.</summary>
    private static byte[] Plugin()
    {
        using var buffer = new MemoryStream();
        using var writer = new BinaryWriter(buffer);
        const int hedrSize = 12;
        writer.Write("TES4"u8);
        writer.Write(4u + 2 + hedrSize); // data size: HEDR tag, its length, its payload
        writer.Write(0u); // flags
        writer.Write(0u); // form id
        writer.Write(0u); // version control info
        writer.Write((ushort)44); // form version of Skyrim SE
        writer.Write((ushort)0);
        writer.Write("HEDR"u8);
        writer.Write((ushort)hedrSize);
        writer.Write(1.7f);
        writer.Write(0); // record count
        writer.Write(0x800u); // next object id
        return buffer.ToArray();
    }

    private IPluginSortOrderVariety Variety => Game.SortOrderManager.GetSortOrderVarieties().OfType<IPluginSortOrderVariety>().Single();

    private static readonly InstallOptions Options = new(false, new HashSet<RelativePath>());

    /// <summary>A list of four mods, Overwrite, a Stock Game folder and the profile's settings, written in no useful order.</summary>
    private ListBuilder List(string modlistTxt = ModlistTxt)
    {
        var list = new ListBuilder();
        var exe = GameExeArchive();
        list.Archives.Add(exe);
        list.Directives.AddRange(
        [
            list.Inline("mods/A/A.esp", Plugin()),
            list.Inline("mods/A/Root/d3d11.dll", EnbFromModA),
            list.Inline("mods/A/Root/root.dll", RootDll),
            list.Inline("mods/B/B.esp", Plugin()),
            list.Inline("mods/C/c.txt", "c"),
            list.Inline("mods/D/d.txt", "d"),
            list.Inline("overwrite/over.txt", "over"),
            list.Inline("profiles/Default/modlist.txt", modlistTxt),
            list.Inline("profiles/Default/plugins.txt", PluginsTxt),
            list.Inline("profiles/Default/loadorder.txt", LoadorderTxt),
            list.Inline("profiles/Default/skyrim.ini", "[General]\nsLanguage=ENGLISH\n"),
            list.Remapped("ModOrganizer.ini", "[General]\nselected_profile=@ByteArray(Default)\n"),
            new FromArchive(P("Stock Game/SkyrimSE.exe"), Hash64(StubExe), StubExe.Length, new ArchiveHashPath(exe.XxHash64, [])),
            list.Inline("Stock Game/d3d11.dll", EnbFromStockGame),
        ]);
        list.Directives.Reverse();
        return list;
    }

    private Dictionary<string, ConflictPriority> PrioritiesOf(WabbajackModlistLoadoutGroup.ReadOnly group)
    {
        var db = Connection.Db;
        var result = new Dictionary<string, ConflictPriority>();
        foreach (var child in LoadoutItem.FindByParent(db, group.Id).OfTypeLoadoutItemGroup())
        {
            var rows = LoadoutItemGroupPriority.FindByTarget(db, child.LoadoutItemGroupId).ToArray();
            rows.Should().ContainSingle($"'{child.AsLoadoutItem().Name}' has exactly one priority row");
            result[child.AsLoadoutItem().Name] = rows[0].Priority;
        }
        return result;
    }

    private async Task<(Loadout.ReadOnly Loadout, WabbajackModlistLoadoutGroup.ReadOnly Group)> InstallList(ListBuilder list)
    {
        var loadout = await CreateLoadout();
        var modlist = await AddModlist(list.ToList(), list.Blobs);
        var (_, group) = await Install(loadout, modlist, Options);
        return (loadout, group);
    }

    [Fact]
    public async Task ModsWinInTheOrderOfModlistTxtWithOverwriteOnTopAndTheGameRootGroupsAtTheBottom()
    {
        var (_, group) = await InstallList(List());

        var priorities = PrioritiesOf(group);

        priorities.Keys.Should().BeEquivalentTo("A", "B", "C", "D", "Overwrite", "Profile settings", "Stock Game");
        priorities["B"].Value.Should().BeGreaterThan(priorities["A"].Value, "the first line of modlist.txt wins");
        priorities["A"].Value.Should().BeGreaterThan(priorities["C"].Value);
        priorities["Overwrite"].Value.Should().BeGreaterThan(priorities["B"].Value);
        priorities["C"].Value.Should().BeGreaterThan(priorities["D"].Value, "a mod with no line sits below the lowest listed mod");
        priorities["D"].Value.Should().BeGreaterThan(priorities["Profile settings"].Value);
        priorities["Profile settings"].Value.Should().BeGreaterThan(priorities["Stock Game"].Value);
        priorities["Stock Game"].Value.Should().BeLessThan(priorities["A"].Value);
    }

    [Fact]
    public async Task ADisabledLineSwitchesItsGroupOffAndTheOthersStayOn()
    {
        var (_, group) = await InstallList(List());

        var disabled = LoadoutItem.FindByParent(Connection.Db, group.Id).OfTypeLoadoutItemGroup()
            .Where(g => g.AsLoadoutItem().IsDisabled).Select(g => g.AsLoadoutItem().Name);

        disabled.Should().Equal("C");
    }

    [Fact]
    public async Task PriorityRowsAreAboveThoseTheLoadoutAlreadyHad()
    {
        var loadout = await CreateLoadout();
        var existing = await InstallMods(loadout);
        var before = LoadoutItemGroupPriority.FindByLoadout(Connection.Db, loadout.LoadoutId).Max(r => r.Priority.Value);
        var list = List();
        var modlist = await AddModlist(list.ToList(), list.Blobs);

        var (_, group) = await Install(loadout, modlist, Options);

        PrioritiesOf(group).Values.Should().OnlyContain(p => p.Value > before);
        LoadoutItemGroupPriority.FindByTarget(Connection.Db, existing).Should().ContainSingle();
    }

    private async Task<LoadoutItemGroupId> InstallMods(Loadout.ReadOnly loadout)
    {
        var archive = await CreateTestArchive(new Dictionary<RelativePath, byte[]> { [P("Data/earlier.txt")] = "earlier"u8.ToArray() });
        var library = await RegisterLocalArchive(archive.Path);
        var result = await LoadoutManager.InstallItem(library.AsLibraryFile().AsLibraryItem(), loadout.LoadoutId);
        return result.LoadoutItemGroup!.Value.LoadoutItemGroupId;
    }

    [Fact]
    public async Task RunningTheJobTwiceLeavesOnePriorityRowPerGroup()
    {
        var list = List();
        var loadout = await CreateLoadout();
        var modlist = await AddModlist(list.ToList(), list.Blobs);

        var (_, first) = await Install(loadout, modlist, Options);
        var firstPriorities = PrioritiesOf(first);
        var (_, second) = await Install(loadout, modlist, Options);

        PrioritiesOf(second).Should().BeEquivalentTo(firstPriorities);
    }

    [Fact]
    public async Task PluginsAreStagedInLoadorderOnTheLoadoutsOwnOrderAndEarlierRowsFollowThem()
    {
        var loadout = await CreateLoadout();
        var earlier = await CreateTestArchive(new Dictionary<RelativePath, byte[]> { [P("Data/Earlier.esp")] = Plugin() });
        await LoadoutManager.InstallItem((await RegisterLocalArchive(earlier.Path)).AsLibraryFile().AsLibraryItem(), loadout.LoadoutId);
        var loadoutOrder = await Variety.GetOrCreateSortOrderFor(loadout.LoadoutId, loadout.LoadoutId);
        using (var tx = Connection.BeginTransaction())
        {
            Variety.StageOrder(loadoutOrder, ["Earlier.esp"], tx);
            await tx.Commit();
        }

        var list = List();
        var modlist = await AddModlist(list.ToList(), list.Blobs);
        var (_, group) = await Install(loadout, modlist, Options);

        Variety.StoredOrder(Refresh(loadout)).Select(row => row.Name).Should().Equal("A.esp", "B.esp", "Earlier.esp");
        PluginSortOrder.Load(Connection.Db, loadoutOrder.Value).SeededFromGameFile.Should().BeTrue();

        var collectionOrder = Variety.GetSortOrderIdFor(CollectionGroupId.From(group.Id), Connection.Db);
        if (collectionOrder.HasValue)
            PluginSortOrder.Load(Connection.Db, collectionOrder.Value.Value).SeededFromGameFile.Should().BeFalse();
    }

    [Fact]
    public async Task ALoadoutWithoutAPluginOrderYetGetsOneFromTheJob()
    {
        // Creating the loadout synchronizes it, which creates its order in line; the manager's subscription would create it
        // again in the background, so it goes first and the order is deleted, leaving the job to create it.
        ((IDisposable)Game.SortOrderManager).Dispose();
        var loadout = await CreateLoadout();
        if (Variety.GetSortOrderIdFor(loadout.LoadoutId, Connection.Db) is { HasValue: true } created)
        {
            using var tx = Connection.BeginTransaction();
            tx.Delete(created.Value.Value, recursive: true);
            await tx.Commit();
        }
        Variety.GetSortOrderIdFor(loadout.LoadoutId, Connection.Db).HasValue.Should().BeFalse();

        var list = List();
        var modlist = await AddModlist(list.ToList(), list.Blobs);
        await Install(loadout, modlist, Options);

        var order = Variety.GetSortOrderIdFor(loadout.LoadoutId, Connection.Db);
        order.HasValue.Should().BeTrue();
        PluginSortOrder.Load(Connection.Db, order.Value.Value).SeededFromGameFile.Should().BeTrue();
    }

    [Fact]
    public async Task TheListIsEnabledWhenNothingWasSkippedAndStaysOffWhenSomethingWas()
    {
        var (_, clean) = await InstallList(List());
        clean.AsCollectionGroup().AsLoadoutItemGroup().AsLoadoutItem().IsDisabled.Should().BeFalse();
        clean.Contains(WabbajackModlistLoadoutGroup.InstalledAt).Should().BeTrue();

        var archive = await AddZip("a.zip", new() { ["base.bin"] = [1, 2, 3] });
        var list = List();
        list.Archives.Add(archive);
        list.Directives.Add(new TransformedTexture(P("mods/A/patched.bin"), Hash64(new byte[] { 1, 2, 3, 4 }), 4, new ArchiveHashPath(archive.XxHash64, [P("base.bin")]), new ImageState(1, 1, 1, "BC7_UNORM")));
        var (_, skipped) = await InstallList(list);

        SkipsOf(skipped).Should().ContainSingle(s => s.Kind == SkipKind.Transform);
        skipped.AsCollectionGroup().AsLoadoutItemGroup().AsLoadoutItem().IsDisabled.Should().BeTrue();
    }

    [Fact]
    public async Task ApplyingTheInstalledListWritesPluginsTxtInTheStagedOrderAndAModBeatsTheStockGame()
    {
        var root = new GamePath(LocationId.Game, "");
        var loadout = await CreateLoadout();
        await SynchronizerService.ChangeDeploymentBackend(GameInstallation, root, DeploymentBackendId.Copy, chosen: true);
        var list = List();
        var modlist = await AddModlist(list.ToList(), list.Blobs);
        await Install(loadout, modlist, Options);

        await Synchronizer.Synchronize(Refresh(loadout));

        var plugins = (await GameInstallation.Locations.ToAbsolutePath(Game.PluginsFile).ReadAllTextAsync())
            .Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        plugins.Where(l => l.EndsWith(".esp")).Should().Equal("*A.esp", "*B.esp");
        (await GameInstallation.Locations.ToAbsolutePath(new GamePath(LocationId.Game, "root.dll")).ReadAllBytesAsync()).Should().Equal(RootDll);
        (await GameInstallation.Locations.ToAbsolutePath(new GamePath(LocationId.Game, "d3d11.dll")).ReadAllBytesAsync())
            .Should().Equal(EnbFromModA, "the mod's copy outranks the Stock Game's");
    }
}
