using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using FluentAssertions;
using Microsoft.Extensions.DependencyInjection;
using NexusMods.Abstractions.Loadouts;
using NexusMods.Hashing.xxHash3;
using NexusMods.Library.Lock;
using NexusMods.MnemonicDB.Abstractions;
using NexusMods.Paths;
using NexusMods.Sdk;
using NexusMods.Sdk.Games;
using NexusMods.Sdk.Hashes;
using NexusMods.Sdk.Library;
using NexusMods.Sdk.Loadouts;
using NexusMods.Sdk.NexusModsApi;
using NexusMods.Sdk.ProxyConsole;
using NexusMods.SingleProcess;

namespace NexusMods.CLI.Tests;

/// <summary>
/// <c>silvermod library verify</c>, <c>export-lock</c> and <c>import-lock</c> against library rows seeded in the
/// test database. Lock files live in a folder of each test's own, not under the app's temporary folder: the isolated
/// game hosts in this assembly share that folder's root, and one of them shutting down can remove a lock between
/// writing it and running the verb.
/// </summary>
public class LibraryLockVerbTests(IServiceProvider provider) : IDisposable
{
    private readonly string _root = Directory.CreateTempSubdirectory("silvermod-lock-verbs-").FullName;

    public void Dispose() => Directory.Delete(_root, recursive: true);

    private AbsolutePath InRoot(string fileName) => FileSystem.Shared.FromUnsanitizedFullPath(Path.Combine(_root, fileName));

    private IConnection Connection => provider.GetRequiredService<IConnection>();

    private static Sha256Value DigestOf(string content) => Sha256Value.From(SHA256.HashData(Encoding.UTF8.GetBytes(content)));

    private async Task<(int ExitCode, string Output)> Run(params string[] args)
    {
        var renderer = new LoggingRenderer();
        var exitCode = await provider.GetRequiredService<CommandLineConfigurator>().RunAsync(args, renderer, CancellationToken.None);
        return (exitCode, string.Join("\n", renderer.Logs.OfType<Text>().Select(t => t.Template)));
    }

    /// <summary>
    /// Adds a library file under a name no other test uses, with the stored digest given (none for an old row).
    /// </summary>
    private async Task<LibraryFile.ReadOnly> AddFile(string fileName, string content, Sha256Value? sha256, Action<ITransaction, LibraryFile.New>? extend = null)
    {
        var bytes = Encoding.UTF8.GetBytes(content);
        using var tx = Connection.BeginTransaction();
        var file = new LibraryFile.New(tx, out var id)
        {
            FileName = fileName,
            Hash = bytes.xxHash3(),
            Size = Size.From((ulong)bytes.Length),
            LibraryItem = new LibraryItem.New(tx, id) { Name = fileName },
        };
        if (sha256 is { } digest) tx.Add(id, LibraryFile.Sha256, digest);
        extend?.Invoke(tx, file);
        var result = await tx.Commit();
        return result.Remap(file);
    }

    private static string UniqueName(string stem) => $"{stem}-{Guid.NewGuid():N}.zip";

    private static string LockText(params (string Id, string Asset, string Sha256)[] entries)
    {
        var builder = new StringBuilder("# Generated by SilverModManager. Pinned mod versions + hashes.\n");
        foreach (var (id, asset, sha256) in entries)
            builder.Append($"\n[{id}]\nversion = \"v1\"\nasset = \"{asset}\"\nsha256 = \"{sha256}\"\nsource = \"github\"\n");
        return builder.ToString();
    }

    private async Task<AbsolutePath> WriteLock(string text)
    {
        var path = InRoot("mods.lock.toml");
        await File.WriteAllTextAsync(path.ToString(), text, TestContext.Current.CancellationToken);
        return path;
    }

    private async Task<Loadout.ReadOnly> CreateLoadout()
    {
        using var tx = Connection.BeginTransaction();
        var metadata = new GameInstallMetadata.New(tx)
        {
            Path = "/tmp/lock-verb-tests-" + Guid.NewGuid(),
            Name = "Lock Verb Game",
            Store = GameStore.Unknown,
            GameId = NexusModsGameId.From(4333),
        };
        var loadout = new Loadout.New(tx)
        {
            Name = "Lock Verbs " + Guid.NewGuid(),
            ShortName = "LV",
            InstallationId = metadata,
            LoadoutKind = LoadoutKind.Default,
            Revision = 0,
            GameVersion = VanityVersion.From("Unknown"),
        };
        var result = await tx.Commit();
        return result.Remap(loadout);
    }

    [Fact]
    public async Task VerifyReportsAMatchingFileAsOkAndExitsZero()
    {
        var asset = UniqueName("ok");
        await AddFile(asset, "ok content", DigestOf("ok content"));
        var path = await WriteLock(LockText(("ok-mod", asset, DigestOf("ok content").ToString())));

        var (exitCode, output) = await Run("library", "verify", "--lock", path.ToString());

        exitCode.Should().Be(0, output);
        output.Should().Contain("[ok] ok-mod: sha256 ok");
    }

    [Fact]
    public async Task VerifyFindsAFileByItsDigestWhenTheLibraryKnowsItUnderAnotherName()
    {
        // A Nexus Mods download keeps the name of the temporary file it was written to, not the archive name a lock records.
        var content = "renamed " + Guid.NewGuid();
        await AddFile(UniqueName("download"), content, DigestOf(content));
        var path = await WriteLock(LockText(("renamed-mod", UniqueName("archive"), DigestOf(content).ToString())));

        var (exitCode, output) = await Run("library", "verify", "--lock", path.ToString());

        exitCode.Should().Be(0, output);
        output.Should().Contain("[ok] renamed-mod: sha256 ok");
    }

    [Fact]
    public async Task VerifyWarnsAboutAFileMissingFromTheLibraryAndStillExitsZero()
    {
        var asset = UniqueName("missing");
        var path = await WriteLock(LockText(("missing-mod", asset, DigestOf("whatever").ToString())));

        var (exitCode, output) = await Run("library", "verify", "--lock", path.ToString());

        exitCode.Should().Be(0, output);
        output.Should().Contain("[warn] missing-mod").And.Contain("not in the library");
    }

    [Fact]
    public async Task VerifyFailsAWrongDigestAndExitsOne()
    {
        var asset = UniqueName("wrong");
        await AddFile(asset, "actual content", DigestOf("actual content"));
        var path = await WriteLock(LockText(("wrong-mod", asset, DigestOf("pinned content").ToString())));

        var (exitCode, output) = await Run("library", "verify", "--lock", path.ToString());

        exitCode.Should().Be(1, output);
        output.Should().Contain("[fail] wrong-mod: HASH MISMATCH").And.Contain(DigestOf("actual content").ToString());
    }

    [Fact]
    public async Task VerifyFailsAnEmptyExpectedDigestEvenWhenTheFileIsThere()
    {
        var asset = UniqueName("empty");
        await AddFile(asset, "content", DigestOf("content"));
        var path = await WriteLock(LockText(("empty-mod", asset, "")));

        var (exitCode, output) = await Run("library", "verify", "--lock", path.ToString());

        exitCode.Should().Be(1, output);
        output.Should().Contain("[fail] empty-mod").And.Contain("no valid sha256");
    }

    [Fact]
    public async Task VerifyFailsAFileWithNoDigestWhoseBytesTheStoreDoesNotHold()
    {
        var asset = UniqueName("gone");
        await AddFile(asset, "never stored", sha256: null);
        var path = await WriteLock(LockText(("gone-mod", asset, DigestOf("never stored").ToString())));

        var (exitCode, output) = await Run("library", "verify", "--lock", path.ToString());

        exitCode.Should().Be(1, output);
        output.Should().Contain("[fail] gone-mod").And.Contain("no longer in the file store");
    }

    [Fact]
    public async Task VerifyPrintsTheWorstLevelAndTheItemsAsJsonWhenAsked()
    {
        var okAsset = UniqueName("json-ok");
        var badAsset = UniqueName("json-bad");
        await AddFile(okAsset, "good", DigestOf("good"));
        await AddFile(badAsset, "bad", DigestOf("bad"));
        var path = await WriteLock(LockText(("a-ok", okAsset, DigestOf("good").ToString()), ("b-bad", badAsset, DigestOf("other").ToString())));

        var (exitCode, output) = await Run("library", "verify", "--lock", path.ToString(), "--json");

        exitCode.Should().Be(1);
        using var document = JsonDocument.Parse(output);
        document.RootElement.GetProperty("worst").GetString().Should().Be("fail");
        var items = document.RootElement.GetProperty("items").EnumerateArray().ToArray();
        items.Select(item => item.GetProperty("level").GetString()).Should().Equal("ok", "fail");
        items[1].GetProperty("message").GetString().Should().Contain("b-bad");
    }

    [Fact]
    public async Task VerifyRejectsALockWithAnUnknownKeyAndExitsOne()
    {
        var path = await WriteLock("[mod]\nversion = \"1\"\nasset = \"a.zip\"\nsha256 = \"ab\"\nsource = \"github\"\nextra = \"x\"\n");

        var (exitCode, output) = await Run("library", "verify", "--lock", path.ToString());

        exitCode.Should().Be(1);
        output.Should().Contain("mod").And.Contain("extra");
    }

    [Fact]
    public async Task ExportLockWritesTheLoadoutsReleaseFilesInTheLockShape()
    {
        var loadout = await CreateLoadout();
        var asset = UniqueName("tool");
        var digest = DigestOf("tool bytes");
        var file = await AddFile(asset, "tool bytes", digest, (tx, lf) =>
        {
            _ = new GitHubReleaseLibraryFile.New(tx, lf.Id) { LibraryFile = lf, Tag = "v0.13.0", AssetName = asset, PinnedSha256 = digest };
            tx.Add(lf.Id, GitHubReleaseLibraryFile.Organization, "garden-of-eyes");
            tx.Add(lf.Id, GitHubReleaseLibraryFile.Repository, "me3");
        });
        using (var tx = Connection.BeginTransaction())
        {
            var group = new LoadoutItemGroup.New(tx, out var id)
            {
                IsGroup = true,
                LoadoutItem = new LoadoutItem.New(tx, id) { Name = "Me3 Host", LoadoutId = loadout.LoadoutId },
            };
            _ = new LibraryLinkedLoadoutItem.New(tx, id) { LibraryItemId = file.Id, LoadoutItemGroup = group };
            await tx.Commit();
        }

        var output = InRoot("out.lock.toml");
        var (exitCode, text) = await Run("library", "export-lock", "--loadout", loadout.Name, "--out", output.ToString());

        exitCode.Should().Be(0, text);
        var written = await File.ReadAllTextAsync(output.ToString(), TestContext.Current.CancellationToken);
        written.Should().Be($"# Generated by SilverModManager. Pinned mod versions + hashes.\n\n[me3-host]\nversion = \"v0.13.0\"\nasset = \"{asset}\"\nsha256 = \"{digest}\"\nsource = \"github\"\n");
    }

    [Fact]
    public async Task ExportLockFailsAndWritesNothingWhenAnItemCannotBePinned()
    {
        var loadout = await CreateLoadout();
        var local = await AddFile(UniqueName("local"), "local", DigestOf("local"));
        using (var tx = Connection.BeginTransaction())
        {
            var group = new LoadoutItemGroup.New(tx, out var id)
            {
                IsGroup = true,
                LoadoutItem = new LoadoutItem.New(tx, id) { Name = "Local", LoadoutId = loadout.LoadoutId },
            };
            _ = new LibraryLinkedLoadoutItem.New(tx, id) { LibraryItemId = local.Id, LoadoutItemGroup = group };
            await tx.Commit();
        }

        var output = InRoot("out.lock.toml");
        var (exitCode, text) = await Run("library", "export-lock", "--loadout", loadout.Name, "--out", output.ToString());

        exitCode.Should().Be(1);
        text.Should().Contain("Local");
        File.Exists(output.ToString()).Should().BeFalse();
    }

    [Fact]
    public async Task ImportLockFailsAnEntryWithAnEmptyDigestAndExitsOne()
    {
        var loadout = await CreateLoadout();
        var path = await WriteLock(LockText(("no-digest", UniqueName("nd"), "")));

        var (exitCode, output) = await Run("library", "import-lock", "--loadout", loadout.Name, "--file", path.ToString());

        exitCode.Should().Be(1, output);
        output.Should().Contain("[failed] no-digest").And.Contain("0 verified");
    }

    [Fact]
    public async Task ImportLockSkipsAFileThatIsAlreadyInTheLibraryAndLinkedAndExitsZero()
    {
        var loadout = await CreateLoadout();
        var asset = UniqueName("present");
        var digest = DigestOf("present bytes");
        var file = await AddFile(asset, "present bytes", digest);
        using (var tx = Connection.BeginTransaction())
        {
            var group = new LoadoutItemGroup.New(tx, out var id)
            {
                IsGroup = true,
                LoadoutItem = new LoadoutItem.New(tx, id) { Name = "Present", LoadoutId = loadout.LoadoutId },
            };
            _ = new LibraryLinkedLoadoutItem.New(tx, id) { LibraryItemId = file.Id, LoadoutItemGroup = group };
            await tx.Commit();
        }

        var path = await WriteLock(LockText(("present-mod", asset, digest.ToString())));
        var (exitCode, output) = await Run("library", "import-lock", "--loadout", loadout.Name, "--file", path.ToString());

        exitCode.Should().Be(0, output);
        output.Should().Contain("[skipped] present-mod").And.Contain("1 already in the library").And.NotContain("[installed]");
    }
}
