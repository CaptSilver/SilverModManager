using FluentAssertions;
using SilverModManager.Wabbajack.Mapping;

namespace SilverModManager.Wabbajack.Tests.Mapping;

public class ModlistTxtTests
{
    private const string Header = "# This file was automatically generated by Mod Organizer.";

    [Fact]
    public void EachPrefixSaysWhetherTheEntryIsOnOffForeignOrASeparator()
    {
        var entries = ModlistTxt.Parse($"{Header}\r\n+A\r\n-B\r\n*Skyrim.esm\r\n+Sep_separator\r\n");

        entries.Should().Equal(
            new ModlistTxtEntry("A", true, false, false),
            new ModlistTxtEntry("B", false, false, false),
            new ModlistTxtEntry("Skyrim.esm", true, false, true),
            new ModlistTxtEntry("Sep_separator", true, true, false));
    }

    [Fact]
    public void TopLineIsHighestPriority()
    {
        // MO2 writes the list from the highest priority down: mo2/modorganizer/src/profile.cpp:259-275 walks
        // m_ModIndexByPriority in reverse ("the priority order was inverted on load so it has to be inverted again").
        // So the order of the file is the order of the result, first entry on top.
        var entries = ModlistTxt.Parse($"{Header}\n+Top\n+Middle\n+Bottom\n");

        entries.Select(e => e.Name).Should().Equal("Top", "Middle", "Bottom");
    }

    [Fact]
    public void LfAndCrlfBothParse_AndBlankAndCommentLinesAreSkipped()
    {
        ModlistTxt.Parse("# a\n\n+A\n   \n#+B\n+C").Select(e => e.Name).Should().Equal("A", "C");
        ModlistTxt.Parse("# a\r\n\r\n+A\r\n+C\r\n").Select(e => e.Name).Should().Equal("A", "C");
    }

    [Fact]
    public void ANameKeepsItsSpacesAndPunctuation()
    {
        ModlistTxt.Parse("+SkyUI 5.2 SE - (patched)\n")[0].Name.Should().Be("SkyUI 5.2 SE - (patched)");
    }
}
